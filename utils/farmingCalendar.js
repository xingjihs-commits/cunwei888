/**
 * 取给定日期所属的节气名
 * @param {Date} date
 * @returns {string}
 */
export function getTodayTerm(date = new Date()) {
  const m = date.getMonth() + 1
  const d = date.getDate()
  let cur = TERMS[TERMS.length - 1][2] // 默认上一节气（跨年时用冬至）
  for (const t of TERMS) {
    if (m > t[0] || (m === t[0] && d >= t[1])) cur = t[2]
  }
  return cur
}

/**
 * 取给定日期的农事建议
 * @param {Date} date
 * @returns {{ term: string, yi: string, ji: string }}
 */
export function getFarmingAdvice(date = new Date()) {
  const term = getTodayTerm(date)
  const a = ADVICE[term] || { yi: '', ji: '' }
  return { term, yi: a.yi, ji: a.ji }
}
